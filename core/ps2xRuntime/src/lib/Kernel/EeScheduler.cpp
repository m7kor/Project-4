namespace
{
    // VU0 is one physical register bank. Guest thread/IRQ frames save EE
    // registers, not an independent vector unit. Generated code still uses a
    // context view, so borrow this bank at execution boundaries and publish it
    // before another frame executes. FBRST/VPU_STAT already have shared-owner
    // helpers and must never be overwritten by these compatibility views.
    void copyVuRegisterBank(R5900Context &target, const R5900Context &source)
    {
        if (&target == &source) return;
        std::memcpy(target.vu0_vf, source.vu0_vf, sizeof(target.vu0_vf));
        std::memcpy(target.vi, source.vi, sizeof(target.vi));
        target.vu0_q = source.vu0_q;
        target.vu0_p = source.vu0_p;
        target.vu0_i = source.vu0_i;
        target.vu0_r = source.vu0_r;
        target.vu0_acc = source.vu0_acc;
        target.vu0_status = source.vu0_status;
        target.vu0_mac_flags = source.vu0_mac_flags;
        target.vu0_clip_flags = source.vu0_clip_flags;
        target.vu0_cmsar0 = source.vu0_cmsar0;
        target.vu0_cmsar1 = source.vu0_cmsar1;
        target.vu0_tpc = source.vu0_tpc;
    }

    // PS2X_TRACE_SYNC_FROM=<vsync>: from that EE vsync on, log every sleep,
    // wakeup, semaphore and event-flag operation (bounded), to find a lost
    // wakeup between guest threads.
    uint32_t traceSyncFromVsync()
    {
        static const uint32_t from = []
        {
            const char *value = std::getenv("PS2X_TRACE_SYNC_FROM");
            return value ? static_cast<uint32_t>(std::strtoul(value, nullptr, 0)) : UINT32_MAX;
        }();
        return from;
    }

    // PS2X_UNPACED=1: drop host-clock pacing so events fire purely on EE
    // cycles. Scheduling then no longer depends on how fast the host runs,
    // which makes runs reproducible (and lets idle phases run flat out).
    bool unpaced()
    {
        static const bool value = std::getenv("PS2X_UNPACED") != nullptr;
        return value;
    }

    // A host deadline that has always passed; distinct from the
    // default-constructed "no deadline" sentinel used by the pacing loop.
    constexpr std::chrono::steady_clock::time_point kHostDeadlinePassed{std::chrono::nanoseconds(1)};

    void traceSync(uint64_t vsync, int current, bool interrupt, uint32_t ra, const char *op, int id, int64_t extra,
                   int result)
    {
        static uint32_t lines = 0;
        if (vsync < traceSyncFromVsync() || lines >= 200000u)
            return;
        ++lines;
        std::cerr << "[EE sync] v=" << vsync << " thread=" << current << (interrupt ? " irq" : "") << " ra=0x"
                  << std::hex << ra << std::dec << ' ' << op << " id=" << id << " x=" << extra << " r=" << result
                  << std::endl;
    }
}

