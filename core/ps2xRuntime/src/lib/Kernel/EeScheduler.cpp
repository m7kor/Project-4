void EeScheduler::reset(uint8_t *rdram, const R5900Context &mainContext)
{
    m_executorThread = std::this_thread::get_id();
    m_rdram = rdram;
    m_readyQueues = {};
    m_threads.clear();
    m_semaphores.clear();
    m_eventFlags.clear();
    m_alarms.clear();
    m_transportCompletions.clear();
    m_transportCompletionSequence = 0;
    m_intcHandlers.clear();
    m_dmacHandlers.clear();
    m_nextThreadId = kFirstThreadId;
    m_nextInvocationThreadId = -1;
    m_nextSemaphoreId = 1;
    m_nextEventFlagId = 1;
    m_nextAlarmId = 1;
    m_nextIntcHandlerId = 1;
    m_nextDmacHandlerId = 1;
    m_intcHeadOrder = 0;
    m_intcTailOrder = 1000;
    m_dmacHeadOrder = 0;
    m_dmacTailOrder = 1000;
    m_enabledIntcMask = 0xFFFFFFFFu;
    m_enabledDmacMask = 0xFFFFFFFFu;
    m_currentThreadId = 0;
    m_rescheduleRequested = false;
    m_timeSliceExpired = false;
    m_insideInterrupt = false;
    m_pendingEeTimerInterrupts = 0u;
    m_eeCycle = 0u;
    m_sliceEndCycle = kDefaultTimeSliceCycles;
    m_stopRequested.store(false, std::memory_order_release);
    m_checkpointPending.store(false, std::memory_order_release);
    m_debugPublishCountdown = 0u;
    {
        std::lock_guard lock(m_eventMutex);
        m_events.clear();
        m_deadlines.clear();
        m_pendingInvocations.clear();
    }
    m_eventSequence = 0;
    m_invocationSequence = 0;
    m_vsyncTick = 0;
    m_vsyncFlagAddress = 0;
    m_vsyncTickAddress = 0;
    m_gsVSyncCallback = 0;
    m_gsVSyncCallbackGp = 0;
    m_gsVSyncCallbackSp = 0;
    m_runtime.memory().gs().vsyncTick.store(0u, std::memory_order_release);
    m_runtime.memory().resetEeTimers();
    copyVuRegisterBank(m_runtime.cpu(), mainContext);

    GuestThread main{};
    main.id = kMainThreadId;
    main.context = mainContext;
    main.entry = mainContext.pc;
    // $sp is live execution state, not the stable initial stack descriptor
    // returned by ReferThreadStatus. SetupThread records that metadata.
    main.stack = 0u;
    main.gp = getRegU32(&mainContext, 28);
    main.initialPriority = 0;
    main.currentPriority = 0;
    main.status = EeThreadStatus::Ready;
    m_threads.emplace(main.id, std::move(main));
    m_readyQueues[0].push_back(kMainThreadId);
    scheduleEvent(m_eeCycle + kVBlankPeriodCycles,
                  std::chrono::steady_clock::now() + kVBlankPeriod,
                  EeEvent{EeEventType::VBlankStart, 0, 0});
    publishSnapshot();
}

void EeScheduler::run()
{
    assertExecutor();
    m_running.store(true, std::memory_order_release);
    auto executeWithVuBank = [this](GuestThread &owner, auto &&execute)
    {
        const int ownerId = owner.id;
        const size_t depth = owner.invocations.size();
        const uint64_t sequence = depth ? owner.invocations.back().sequence : 0;
        copyVuRegisterBank(owner.activeContext(), m_runtime.cpu());
        auto publish = [&]
        {
            // invokeCurrent may grow/reallocate the invocation vector. Resolve
            // the original frame by identity after execution; never retain its
            // reference across the guest call or read a newly pushed child.
            GuestThread *live = thread(ownerId);
            if (!live) return; // ExitDeleteThread published before deletion.
            if (!depth) copyVuRegisterBank(m_runtime.cpu(), live->context);
            else if (live->invocations.size() >= depth &&
                     live->invocations[depth - 1].sequence == sequence)
                copyVuRegisterBank(m_runtime.cpu(), live->invocations[depth - 1].context);
        };
        try { execute(owner.activeContext()); }
        catch (...) { publish(); throw; }
        publish();
    };
    const bool traceDispatch = std::getenv("PS2X_TRACE_EE") != nullptr;
    uint32_t traceCount = 0u;
    const bool traceChanges = traceDispatch && std::getenv("PS2X_TRACE_EE_CHANGES") != nullptr;
    std::vector<uint32_t> previousTraceWords;
    uint32_t previousDispatchPc = 0u;
    int previousDispatchThread = 0;
    std::vector<uint32_t> traceWords;
    std::vector<uint32_t> tracePcs;
    // Keep the bounded diagnostic budget for selected late callbacks instead
    // of consuming it during boot. Options are read once on the EE executor.
    const char *tracePcSelection = traceDispatch ? std::getenv("PS2X_TRACE_EE_PCS") : nullptr;
    if (tracePcSelection)
    {
        const char *cursor = tracePcSelection;
        while (*cursor && tracePcs.size() < 16u)
        {
            char *end = nullptr;
            const unsigned long address = std::strtoul(cursor, &end, 0);
            if (end == cursor || (*end && *end != ',') ||
                address > PS2_RAM_SIZE - 4u || (address & 3u))
            {
                std::cerr << "[EE trace] Invalid aligned PC selector\n";
                break;
            }
            tracePcs.push_back(static_cast<uint32_t>(address));
            cursor = *end == ',' ? end + 1 : end;
        }
    }
    if (traceDispatch)
    {
        if (const char *addresses = std::getenv("PS2X_TRACE_WORDS"))
        {
            while (*addresses && traceWords.size() < 16u)
            {
                char *end = nullptr;
                const unsigned long address = std::strtoul(addresses, &end, 0);
                if (end == addresses || (*end != ',' && *end != '\0') ||
                    address > PS2_RAM_SIZE - sizeof(uint32_t) || (address & 3u))
                {
                    std::cerr << "[EE trace] Invalid aligned RAM watch address\n";
                    break;
                }
                traceWords.push_back(static_cast<uint32_t>(address));
                addresses = *end == ',' ? end + 1 : end;
            }
        }
    }

    while (!m_stopRequested.load(std::memory_order_acquire))
    {
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseBegin(lodestone::GuestPcProfile::Phase::Events);
#endif
        processPendingEvents();
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseAdd(lodestone::GuestPcProfile::Phase::Events);
#endif
        if (m_stopRequested.load(std::memory_order_acquire))
        {
            break;
        }

        if (m_currentThreadId == 0)
        {
            GuestThread *next = selectReady();
            if (!next && m_pendingInvocations.empty())
            {
                copyMainContextToRuntime();
                publishIdleDebugContext();
                publishSnapshot();
                waitForEvent();
                continue;
            }
            if (next)
            {
                makeRunning(*next);
            }
            else
            {
                GuestThread *owner = &acquireInvocationThread();
                GuestInvocation invocation = std::move(m_pendingInvocations.front());
                m_pendingInvocations.pop_front();
                owner->status = EeThreadStatus::Running;
                m_currentThreadId = owner->id;
                renewTimeSlice();
                prepareQueuedInvocation(invocation);
                owner->invocations.push_back(std::move(invocation));
            }
        }

        GuestThread *running = currentThread();
        assert(running != nullptr);
        if (running->resumeCompletion)
        {
            auto completion = std::move(running->resumeCompletion);
            running->resumeCompletion = {};
            try
            {
                executeWithVuBank(*running, [&](R5900Context &active) { completion(active); });
            }
            catch (const EeDispatcherTransfer &)
            {
            }
            if (m_currentThreadId == 0)
            {
                continue;
            }
        }
        R5900Context &context = running->activeContext();
        if (m_debugPublishCountdown == 0u)
        {
            copyMainContextToRuntime();
            publishSnapshot();
            m_debugPublishCountdown = kDebugPublishDispatchInterval - 1u;
        }
        else
        {
            --m_debugPublishCountdown;
        }

        publishDebugContext(context);

        if (context.pc == 0u)
        {
            if (!running->invocations.empty())
            {
                GuestInvocation completed = std::move(running->invocations.back());
                running->invocations.pop_back();
                if (completed.onComplete)
                {
                    try
                    {
                        executeWithVuBank(*running, [&](R5900Context &active) {
                            completed.onComplete(completed.context, active);
                        });
                    }
                    catch (const EeDispatcherTransfer &)
                    {
                    }
                }
                continue;
            }
            makeDormant(*running);
            m_currentThreadId = 0;
            copyMainContextToRuntime();
            publishIdleDebugContext();
            publishSnapshot();
            continue;
        }

        if (!m_pendingInvocations.empty() && running->invocations.empty())
        {
            GuestInvocation invocation = std::move(m_pendingInvocations.front());
            m_pendingInvocations.pop_front();
            prepareQueuedInvocation(invocation);
            running->invocations.push_back(std::move(invocation));
            continue;
        }

        if (!m_runtime.hasFunction(context.pc))
        {
            if (!running->invocations.empty())
            {
                context.pc = 0u;
            }
            else
            {
                m_runtime.reportMissingFunction(m_rdram,
                                                &context,
                                                context.pc,
                                                context.pc,
                                                PS2Runtime::GuestBranchKind::DirectJump,
                                                "EE scheduler");
                makeDormant(*running);
                m_currentThreadId = 0;
            }
            continue;
        }
        PS2Runtime::RecompiledFunction function = m_runtime.lookupFunction(context.pc);

#if defined(PS2X_GUEST_PC_PROFILE)
        // LODESTONE PATCH 12: one sample per guest dispatch. Compiled out
        // entirely in an OFF build - EeScheduler::run is the hottest loop in
        // the runtime, and a runtime env flag cannot make a hot-path probe free
        // (DC2 rules 12c/16).
        lodestone::sampleGuestPc(context.pc);
#endif

#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseBegin(lodestone::GuestPcProfile::Phase::Checkpoint);
#endif
        if (checkpointDue(kGuestDispatchCycles))
        {
#if defined(PS2X_GUEST_PC_PROFILE)
            lodestone::GuestPcProfile::instance().phaseAdd(lodestone::GuestPcProfile::Phase::Checkpoint);
#endif
            continue;
        }
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseAdd(lodestone::GuestPcProfile::Phase::Checkpoint);
#endif

        try
        {
#if defined(PS2X_GUEST_PC_PROFILE)
            lodestone::GuestPcProfile::instance().phaseBegin(lodestone::GuestPcProfile::Phase::Guest);
#endif
            m_insideInterrupt = !running->invocations.empty() && running->invocations.back().kind == GuestInvocationKind::Interrupt;
            m_guestExecuting.store(true, std::memory_order_release);
            const bool selectedTracePc = !tracePcSelection ||
                std::find(tracePcs.begin(), tracePcs.end(), context.pc) != tracePcs.end();
            bool changedTraceWords = false;
            if (traceChanges && traceCount < 8192u && !traceWords.empty())
            {
                changedTraceWords = previousTraceWords.size() != traceWords.size();
                previousTraceWords.resize(traceWords.size());
                for (size_t i = 0; i < traceWords.size(); ++i)
                {
                    uint32_t value = 0u;
                    if (m_rdram) std::memcpy(&value, m_rdram + traceWords[i], sizeof(value));
                    changedTraceWords |= previousTraceWords[i] != value;
                    previousTraceWords[i] = value;
                }
            }
            if (traceDispatch && selectedTracePc && (!traceChanges || changedTraceWords) && traceCount < 8192u)
            {
                ++traceCount;
                std::cerr << "[EE dispatch] thread=" << running->id
                          << " pc=0x" << std::hex << context.pc
                          << " ra=0x" << getRegU32(&context, 31)
                          << " sp=0x" << getRegU32(&context, 29)
                          << " a0=0x" << getRegU32(&context, 4)
                          << " a2=0x" << getRegU32(&context, 6)
                          << " a3=0x" << getRegU32(&context, 7)
                          << " s0=0x" << getRegU32(&context, 16)
                          << " s1=0x" << getRegU32(&context, 17)
                          << " s3=0x" << getRegU32(&context, 19)
                          << " v0=0x" << getRegU32(&context, 2);
                if (traceChanges)
                {
                    // Boundary attribution only: the previous dispatch can
                    // include nested calls and event processing, not one store.
                    std::cerr << " previous_pc=0x" << previousDispatchPc
                              << " previous_thread=" << std::dec << previousDispatchThread << std::hex;
                }
                // Read on the EE executor, never the presentation thread.
                // RAM-only, bounded, opt-in observations; no guest writes.
                for (const uint32_t address : traceWords)
                {
                    uint32_t value = 0u;
                    if (m_rdram) std::memcpy(&value, m_rdram + address, sizeof(value));
                    std::cerr << " ram[0x" << address << "]=0x" << value;
                }
                std::cerr << std::dec << '\n';
                if (traceCount == 8192u)
                    std::cerr << "[EE trace] Row limit reached; subsequent observations omitted\n";
            }
            if (traceChanges)
            {
                previousDispatchPc = context.pc;
                previousDispatchThread = running->id;
            }
            executeWithVuBank(*running, [&](R5900Context &active) {
                function(m_rdram, &active, &m_runtime);
            });
            m_guestExecuting.store(false, std::memory_order_release);
            m_insideInterrupt = false;
        }
        catch (const EeDispatcherTransfer &)
        {
            m_guestExecuting.store(false, std::memory_order_release);
            m_insideInterrupt = false;
        }
        catch (...)
        {
            m_guestExecuting.store(false, std::memory_order_release);
            m_running.store(false, std::memory_order_release);
            publishSnapshot();
            throw;
        }
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseAdd(lodestone::GuestPcProfile::Phase::Guest);
#endif

        processPendingEvents();
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseBegin(lodestone::GuestPcProfile::Phase::Other);
#endif
        if (m_rescheduleRequested && m_currentThreadId != 0)
        {
            GuestThread *preempted = currentThread();
            assert(preempted != nullptr);
            enqueueReady(*preempted, !m_timeSliceExpired);
            m_currentThreadId = 0;
            m_rescheduleRequested = false;
            m_timeSliceExpired = false;
        }
#if defined(PS2X_GUEST_PC_PROFILE)
        lodestone::GuestPcProfile::instance().phaseAdd(lodestone::GuestPcProfile::Phase::Other);
#endif
    }

    m_guestExecuting.store(false, std::memory_order_release);
    m_running.store(false, std::memory_order_release);
#if defined(PS2X_GUEST_PC_PROFILE)
    // Whole-run lifetime summary, complementing the periodic window reports.
    // Periodic windows exist because the interesting failures have to be killed
    // rather than exited; this one exists for a clean shutdown.
    lodestone::reportGuestPcTotals();
#endif
    copyMainContextToRuntime();
    publishSnapshot();
}

void EeScheduler::requestStop()
{
    m_stopRequested.store(true, std::memory_order_release);
    m_checkpointPending.store(true, std::memory_order_release);
    m_eventCv.notify_all();
}

void EeScheduler::postEvent(EeEvent event)
{
    if (event.type == EeEventType::Stop)
    {
        requestStop();
        return;
    }

    {
        std::lock_guard lock(m_eventMutex);
        m_events.push_back(event);
        m_checkpointPending.store(true, std::memory_order_release);
    }
    m_eventCv.notify_one();
}

bool EeScheduler::checkpointDue(uint32_t cycles) noexcept
{
    accountCycles(cycles);

    if (m_checkpointPending.load(std::memory_order_acquire) ||
        m_stopRequested.load(std::memory_order_acquire))
    {
        return true;
    }

    const uint64_t nextEventCycle = m_nextDeadlineCycle.load(std::memory_order_acquire);
    if (nextEventCycle != 0u && m_eeCycle >= nextEventCycle)
    {
        m_checkpointPending.store(true, std::memory_order_release);
        return true;
    }

    if (m_eeCycle < m_sliceEndCycle)
    {
        return false;
    }

    const GuestThread *running = currentThread();
    if (running != nullptr && hasReadyAtOrAbovePriority(running->currentPriority))
    {
        m_rescheduleRequested = true;
        m_timeSliceExpired = true;
        return true;
    }

    renewTimeSlice();
    return false;
}

void EeScheduler::accountCycles(uint32_t cycles) noexcept
{
    const uint64_t elapsed = std::max<uint64_t>(1u, cycles);
    m_eeCycle += elapsed;
    m_pendingEeTimerInterrupts |= m_runtime.memory().advanceEeTimers(elapsed);
    m_runtime.advanceIopEeCycles(elapsed);
    if (m_pendingEeTimerInterrupts != 0u)
    {
        m_checkpointPending.store(true, std::memory_order_release);
    }
}

void EeScheduler::scheduleTransportCompletion(uint64_t delayCycles, std::function<void()> completion)
{
    assertExecutor();
    if (!completion) return;
    delayCycles = std::max<uint64_t>(1u, delayCycles);
    if (delayCycles > std::numeric_limits<uint64_t>::max() - m_eeCycle)
        throw std::overflow_error("Transport completion deadline overflow");
    const uint64_t token = ++m_transportCompletionSequence;
    m_transportCompletions.emplace(token, std::move(completion));
    scheduleEvent(m_eeCycle + delayCycles, std::chrono::steady_clock::now(),
                  EeEvent{EeEventType::TransportCompletion, 0u, token});
}

bool EeScheduler::isExecutingGuest() const noexcept
{
    return m_guestExecuting.load(std::memory_order_acquire);
}

void EeScheduler::setupCurrentThread(uint32_t stack, uint32_t stackSize, uint32_t gp)
{
    assertExecutor();
    GuestThread *target = currentThread();
    if (!target)
    {
        return;
    }

    target->stack = stack;
    target->stackSize = stackSize;
    target->gp = gp;
    publishSnapshot();
}

int EeScheduler::createThread(const EeThreadCreateParams &params)
{
    assertExecutor();
    if (params.priority < 0 || params.priority >= kPriorityCount)
    {
        return KE_ILLEGAL_PRIORITY;
    }

    const int id = allocateThreadId();
    if (id == 0)
    {
        return KE_ERROR;
    }

    GuestThread thread{};
    thread.id = id;
    thread.entry = params.entry;
    thread.stack = params.stack;
    thread.stackSize = params.stackSize;
    thread.gp = params.gp;
    thread.attr = params.attr;
    thread.option = params.option;
    thread.initialPriority = params.priority;
    thread.currentPriority = params.priority;
    thread.status = EeThreadStatus::Dormant;
    m_threads.emplace(id, std::move(thread));
    if (traceSyncFromVsync() != UINT32_MAX)
        std::cerr << "[EE thread create] id=" << id << " entry=0x" << std::hex << params.entry << " stack=0x"
                  << params.stack << " size=0x" << params.stackSize << std::dec << " priority=" << params.priority
                  << std::endl;
    publishSnapshot();
    return id;
}

int EeScheduler::deleteThread(int id, uint32_t &ownedStack)
{
    assertExecutor();
    ownedStack = 0;
    if (id <= kMainThreadId)
    {
        return KE_ILLEGAL_THID;
    }
    auto it = m_threads.find(id);
    if (it == m_threads.end())
    {
        return KE_UNKNOWN_THID;
    }
    if (it->second.status != EeThreadStatus::Dormant)
    {
        return KE_NOT_DORMANT;
    }
    if (it->second.ownsStack)
    {
        ownedStack = it->second.stack;
    }
    m_threads.erase(it);
    releaseInvocationStacks(id);
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::startThread(int id, uint32_t arg, const R5900Context &caller, bool interruptSafe)
{
    assertExecutor();
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->status != EeThreadStatus::Dormant)
    {
        return KE_NOT_DORMANT;
    }

    target->context = R5900Context{};
    target->context.pc = target->entry;
    target->arg = arg;
    target->suspendCount = 0;
    target->wakeupCount = 0;
    target->wait = {};
    SET_GPR_U32(&target->context, 4, arg);
    SET_GPR_U32(&target->context, 28, target->gp != 0u ? target->gp : getRegU32(&caller, 28));
    const uint32_t stackTop = target->stack != 0u
                                  ? (target->stack + target->stackSize) & ~0xFu
                                  : getRegU32(&caller, 29);
    SET_GPR_U32(&target->context, 29, stackTop);
    SET_GPR_U32(&target->context, 31, 0u);
    enqueueReady(*target);
    requestPreemptionIfHigher(*target, interruptSafe);
    publishSnapshot();
    return KE_OK;
}

[[noreturn]] void EeScheduler::exitCurrent(bool deleteThreadRecord)
{
    assertExecutor();
    GuestThread *exiting = currentThread();
    assert(exiting != nullptr);
    const int id = exiting->id;
    const uint32_t ownedStack = deleteThreadRecord && exiting->ownsStack ? exiting->stack : 0u;
    copyVuRegisterBank(m_runtime.cpu(), exiting->activeContext());
    makeDormant(*exiting);
    m_currentThreadId = 0;
    if (deleteThreadRecord && id != kMainThreadId)
    {
        m_threads.erase(id);
        releaseInvocationStacks(id);
    }
    if (ownedStack != 0u)
    {
        m_runtime.guestFree(ownedStack);
    }
    publishSnapshot();
    throw EeDispatcherTransfer{};
}

int EeScheduler::terminateThread(int id, uint32_t &ownedStack, bool interruptSafe)
{
    assertExecutor();
    ownedStack = 0;
    if (id == 0 || id == m_currentThreadId)
    {
        return KE_ILLEGAL_THID;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->status == EeThreadStatus::Dormant)
    {
        return KE_DORMANT;
    }
    if (target->ownsStack)
    {
        ownedStack = target->stack;
        target->ownsStack = false;
    }
    makeDormant(*target);
    (void)interruptSafe;
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::suspendThread(int id, bool interruptSafe)
{
    assertExecutor();
    if (id == 0)
    {
        id = m_currentThreadId;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->status == EeThreadStatus::Dormant)
    {
        return KE_DORMANT;
    }

    // EE suspension is a state, not a nesting counter. Repeated SuspendThread
    // calls on SUSPEND/WAITSUSPEND have no effect (ps2tek BIOS 37h/38h).
    if (target->status == EeThreadStatus::Suspended ||
        target->status == EeThreadStatus::WaitingSuspended)
    {
        return KE_OK;
    }
    target->suspendCount = 1;
    switch (target->status)
    {
    case EeThreadStatus::Running:
        target->status = EeThreadStatus::Suspended;
        m_currentThreadId = 0;
        m_rescheduleRequested = true;
        break;
    case EeThreadStatus::Ready:
        removeReady(*target);
        target->status = EeThreadStatus::Suspended;
        break;
    case EeThreadStatus::Waiting:
        target->status = EeThreadStatus::WaitingSuspended;
        break;
    case EeThreadStatus::WaitingSuspended:
    case EeThreadStatus::Suspended:
        break;
    case EeThreadStatus::Dormant:
        break;
    }
    if (interruptSafe && m_insideInterrupt)
    {
        m_rescheduleRequested = true;
    }
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::resumeThread(int id, bool interruptSafe)
{
    assertExecutor();
    if (id == 0)
    {
        return KE_ILLEGAL_THID;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->suspendCount == 0)
    {
        return KE_NOT_SUSPEND;
    }
    target->suspendCount = 0;
    if (target->status == EeThreadStatus::WaitingSuspended)
    {
        target->status = EeThreadStatus::Waiting;
    }
    else if (target->status == EeThreadStatus::Suspended)
    {
        enqueueReady(*target);
        requestPreemptionIfHigher(*target, interruptSafe);
    }
    publishSnapshot();
    return KE_OK;
}

void EeScheduler::sleepCurrent()
{
    assertExecutor();
    traceSync(m_vsyncTick, m_currentThreadId, m_insideInterrupt, currentThread() ? getRegU32(&currentThread()->activeContext(), 31) : 0u, "sleep", m_currentThreadId, currentThread() ? currentThread()->wakeupCount : 0u, 0);
    GuestThread *self = currentThread();
    assert(self != nullptr);
    if (self->wakeupCount != 0u)
    {
        --self->wakeupCount;
        setReturnS32(&self->activeContext(), KE_OK);
        return;
    }
    blockCurrent(EeWaitState{EeWaitReason::Sleep, std::monostate{}});
}

int EeScheduler::wakeupThread(int id, bool interruptSafe)
{
    assertExecutor();
    traceSync(m_vsyncTick, m_currentThreadId, m_insideInterrupt, currentThread() ? getRegU32(&currentThread()->activeContext(), 31) : 0u, interruptSafe ? "iwakeup" : "wakeup", id, thread(id) ? static_cast<int>(thread(id)->status) : -1, 0);
    // Only WakeupThread rejects the caller itself. iWakeupThread runs in an
    // interrupt handler, where the "current" thread is merely the one that
    // was interrupted: libsif's RPC end function wakes the calling thread this
    // way, and when the reply interrupt lands before that thread reaches
    // SleepThread the wakeup must be counted, or the thread sleeps forever.
    if (id == 0 || (!interruptSafe && id == m_currentThreadId))
    {
        return KE_ILLEGAL_THID;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->status == EeThreadStatus::Dormant)
    {
        return KE_DORMANT;
    }
    if ((target->status == EeThreadStatus::Waiting || target->status == EeThreadStatus::WaitingSuspended) &&
        target->wait.reason == EeWaitReason::Sleep)
    {
        makeReady(*target, KE_OK, interruptSafe);
    }
    else
    {
        ++target->wakeupCount;
    }
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::cancelWakeup(int id)
{
    assertExecutor();
    if (id == 0)
    {
        id = m_currentThreadId;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    const int old = static_cast<int>(target->wakeupCount);
    target->wakeupCount = 0;
    publishSnapshot();
    return old;
}

int EeScheduler::changePriority(int id, int priority, bool interruptSafe, int &oldPriority)
{
    assertExecutor();
    if (priority < 0 || priority >= kPriorityCount)
    {
        return KE_ILLEGAL_PRIORITY;
    }
    if (id == 0)
    {
        id = m_currentThreadId;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    oldPriority = target->currentPriority;
    if (target->status == EeThreadStatus::Ready)
    {
        removeReady(*target);
        target->currentPriority = priority;
        enqueueReady(*target);
        requestPreemptionIfHigher(*target, interruptSafe);
    }
    else
    {
        target->currentPriority = priority;
        if (target->status == EeThreadStatus::Running)
        {
            for (int p = 0; p < target->currentPriority; ++p)
            {
                if (!m_readyQueues[p].empty())
                {
                    m_rescheduleRequested = true;
                    break;
                }
            }
        }
    }
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::rotateReadyQueue(int priority, bool interruptSafe)
{
    assertExecutor();
    if (priority == 0)
    {
        const GuestThread *self = currentThread();
        priority = self ? self->currentPriority : 0;
    }
    if (priority < 0 || priority >= kPriorityCount)
    {
        return KE_ILLEGAL_PRIORITY;
    }

    GuestThread *self = currentThread();
    if (self && self->currentPriority == priority)
    {
        enqueueReady(*self);
        m_currentThreadId = 0;
        m_rescheduleRequested = true;
    }
    else
    {
        auto &queue = m_readyQueues[priority];
        if (queue.size() > 1u)
        {
            const int head = queue.front();
            queue.pop_front();
            queue.push_back(head);
        }
    }
    (void)interruptSafe;
    publishSnapshot();
    return KE_OK;
}

int EeScheduler::releaseWait(int id, bool interruptSafe)
{
    assertExecutor();
    if (id == 0)
    {
        return KE_ILLEGAL_THID;
    }
    GuestThread *target = thread(id);
    if (!target)
    {
        return KE_UNKNOWN_THID;
    }
    if (target->status != EeThreadStatus::Waiting && target->status != EeThreadStatus::WaitingSuspended)
    {
        return KE_NOT_WAIT;
    }
    removeFromWaitObject(*target);
    makeReady(*target, KE_RELEASE_WAIT, interruptSafe);
    publishSnapshot();
    return KE_OK;
}

void EeScheduler::transferIfRequested(bool interruptSafe)
{
    assertExecutor();
    if (interruptSafe || m_insideInterrupt || !m_rescheduleRequested)
    {
        return;
    }
    if (m_currentThreadId != 0)
    {
        GuestThread *self = currentThread();
        assert(self != nullptr);
        enqueueReady(*self, true);
        m_currentThreadId = 0;
    }
    m_rescheduleRequested = false;
    m_timeSliceExpired = false;
    publishSnapshot();
    throw EeDispatcherTransfer{};
}

int EeScheduler::createSemaphore(int initCount, int maxCount, uint32_t attr, uint32_t option)
{
    assertExecutor();
    if (maxCount <= 0 || initCount < 0 || initCount > maxCount)
    {
        return KE_ERROR;
    }
    const int id = allocatePositiveId(m_nextSemaphoreId, m_semaphores);
    if (id == 0)
    {
        return KE_ERROR;
    }
    EeSemaphore semaphore{};
    semaphore.id = id;
    semaphore.count = initCount;
    semaphore.maxCount = maxCount;
    semaphore.initCount = initCount;
    semaphore.attr = attr;
    semaphore.option = option;
    m_semaphores.emplace(id, std::move(semaphore));
    publishSnapshot();
    return id;
}

int EeScheduler::deleteSemaphore(int id, bool interruptSafe)
{
    assertExecutor();
    auto it = m_semaphores.find(id);
    if (it == m_semaphores.end())
    {
        return KE_UNKNOWN_SEMID;
    }
    std::deque<int> waiters = std::move(it->second.waiters);
    m_semaphores.erase(it);
    for (const int threadId : waiters)
    {
        if (GuestThread *waiter = thread(threadId))
        {
            makeReady(*waiter, KE_WAIT_DELETE, interruptSafe);
        }
    }
    publishSnapshot();
    return id;
}

int EeScheduler::signalSemaphore(int id, bool interruptSafe)
{
    assertExecutor();
    traceSync(m_vsyncTick, m_currentThreadId, m_insideInterrupt, currentThread() ? getRegU32(&currentThread()->activeContext(), 31) : 0u, interruptSafe ? "isignal" : "signal", id, semaphore(id) ? semaphore(id)->count : -1, 0);
    EeSemaphore *object = semaphore(id);
    if (!object)
    {
        return KE_UNKNOWN_SEMID;
    }
    if (!object->waiters.empty())
    {
        const int waiterId = object->waiters.front();
        object->waiters.pop_front();
        GuestThread *waiter = thread(waiterId);
        assert(waiter != nullptr);
        makeReady(*waiter, id, interruptSafe);
        publishSnapshot();
        return id;
    }
    if (object->count == object->maxCount)
    {
        return KE_SEMA_OVF;
    }
    ++object->count;
    publishSnapshot();
    return id;
}

int EeScheduler::pollSemaphore(int id)
{
    assertExecutor();
    EeSemaphore *object = semaphore(id);
    if (!object)
    {
        return KE_UNKNOWN_SEMID;
    }
    if (object->count == 0)
    {
        return KE_SEMA_ZERO;
    }
    --object->count;
    publishSnapshot();
    return id;
}

void EeScheduler::waitSemaphore(int id)
{
    assertExecutor();
    traceSync(m_vsyncTick, m_currentThreadId, m_insideInterrupt, currentThread() ? getRegU32(&currentThread()->activeContext(), 31) : 0u, "waitsema", id, semaphore(id) ? semaphore(id)->count : -1, 0);
    EeSemaphore *object = semaphore(id);
    if (!object)
    {
        GuestThread *self = currentThread();
        assert(self != nullptr);
        setReturnS32(&self->activeContext(), KE_UNKNOWN_SEMID);
        return;
    }
    if (object->count != 0)
    {
        --object->count;
        GuestThread *self = currentThread();
        assert(self != nullptr);
        setReturnS32(&self->activeContext(), id);
        publishSnapshot();
        return;
    }
    GuestThread *self = currentThread();
    assert(self != nullptr);
    object->waiters.push_back(self->id);
    blockCurrent(EeWaitState{EeWaitReason::Semaphore, EeSemaphoreWait{id}});
}

